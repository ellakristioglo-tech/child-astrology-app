import fs from 'node:fs';

const read = (file) => fs.readFileSync(file, 'utf8');
const fail = (message) => {
  console.error(`iOS preflight failed: ${message}`);
  process.exitCode = 1;
};

const config = JSON.parse(read('capacitor.config.json'));
if (config.appName !== 'Child Astrology') fail('Capacitor appName must be Child Astrology');
if (config.appId !== 'com.childastrology.app') fail('unexpected iOS bundle identifier');

const icon = fs.statSync('resources/AppIcon-1024.png');
if (icon.size < 100_000) fail('App Store icon is missing or unexpectedly small');

const auth = read('auth-gate.js');
if (/424242/.test(auth)) fail('client-side review bypass code is present');
if (!/signInWithOtp/.test(auth)) fail('Supabase OTP flow is missing');
if (!/functions\.invoke\('delete-user'\)/.test(auth)) fail('server account deletion is missing');

const analytics = read('analytics.js');
if (!/analytics_storage:'denied'/.test(analytics)) fail('analytics is not denied by default');

const listing = read('compliance/APP_STORE_LISTING.md');
const appeal = read('compliance/APP_REVIEW_APPEAL_43b.md');
const review = read('compliance/APP_REVIEW_REPLY.md');
for (const [name, value] of [['listing', listing], ['appeal', appeal], ['review reply', review]]) {
  if (/Child Compass|Kindkompas/.test(value)) fail(`${name} still contains the rejected rename`);
  if (/\[REVIEWER INBOX\]|\[INBOX ACCESS INSTRUCTIONS\]|\[phone\]/.test(value)) {
    fail(`${name} contains an unresolved App Review placeholder`);
  }
}

if (!fs.existsSync('assets/cities-15000.min.json')) {
  console.warn('iOS preflight note: city dataset is generated by the build workflow.');
}

if (!process.exitCode) console.log('iOS preflight passed.');
